// Generates FRENCH_REVIEW.md from the shipped XML (TRANSLATIONS.md, 2026-09-30). Run from the repo root.
const fs = require('fs'), path = require('path');
const { execSync } = require('child_process');
const dec = s => s.replace(/&lt;/g,'<').replace(/&gt;/g,'>').replace(/&quot;/g,'"').replace(/&apos;/g,"'").replace(/&amp;/g,'&').trim();
const cell = s => s.replace(/\|/g,'\|').replace(/\n/g,' ');
const defsDir = 'Mod/Defs/ThingDefs_Buildings', frDir = 'Mod/Languages/French/DefInjected/ThingDef';
const rev = execSync('git rev-parse --short HEAD').toString().trim();
let out = `# French review — Ancient Buildings Renew (unofficial)\n\nGenerated by \`_tools/make-french-review.cjs\` from the shipped XML, revision \`${rev}\` (working tree at generation time).\n\n` +
 `Original language: this mod has no source in another language. The "Original" column repeats the English Def value, as TRANSLATIONS.md asks. No text addresses a pawn, so no \`{PAWN_gender ? ...}\` switch applies. No text is doubted by the session (no \`?\` column).\n`;
for (const f of fs.readdirSync(frDir).filter(f=>f.endsWith('.xml')).sort()) {
  const en = {};
  const src = fs.readFileSync(path.join(defsDir, f), 'utf8');
  for (const m of src.matchAll(/<ThingDef\b[^>]*>([\s\S]*?)<\/ThingDef>/g)) {
    const dn = /<defName>([^<]+)<\/defName>/.exec(m[1]); if (!dn) continue;
    for (const k of ['label','description']) { const v = new RegExp(`<${k}>([^]*?)</${k}>`).exec(m[1]); if (v) en[`${dn[1]}.${k}`] = dec(v[1]); }
  }
  out += `\n## DefInjected/ThingDef/${f}\n\n| Key | Original | English | French |\n|---|---|---|---|\n`;
  for (const m of fs.readFileSync(path.join(frDir, f), 'utf8').matchAll(/<([A-Za-z0-9_]+\.(?:label|description))>([\s\S]*?)<\/\1>/g)) {
    const e = en[m[1]] ?? '**MISSING in Defs**';
    out += `| \`${m[1]}\` | ${cell(e)} | ${cell(e)} | ${cell(dec(m[2]))} |\n`;
  }
}
fs.writeFileSync('FRENCH_REVIEW.md', out);
